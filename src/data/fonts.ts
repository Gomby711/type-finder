import type { FontMatch } from "../types";

// Google Fonts: open-license, so every entry here gets a real, live,
// in-browser preview (see lib/loadGoogleFonts.ts) and a working
// fonts.google.com specimen link.
function g(
  name: string,
  category: FontMatch["category"],
  condensed = false,
): FontMatch {
  return {
    id: `g-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name,
    category,
    condensed,
    source: "google",
    foundry: "Google Fonts",
  };
}

// Adobe Fonts: Adobe only serves these through a licensed, account-bound
// "web project" kit — there's no open embed API like Google's, so these
// entries are listed (real name + real foundry + a real fonts.adobe.com
// search link) but rendered with a fallback typeface, not a live preview.
function a(
  name: string,
  category: FontMatch["category"],
  foundry: string,
  condensed = false,
): FontMatch {
  return {
    id: `a-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    name,
    category,
    condensed,
    source: "adobe",
    foundry,
  };
}

