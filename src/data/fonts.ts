export const FONT_CATALOG: FontMatch[] = [...GOOGLE_FONTS, ...ADOBE_FONTS];

export function googleFontsUrl(name: string): string {
  return `https://fonts.google.com/specimen/${name.replace(/ /g, "+")}`;
}

export function adobeFontsUrl(name: string): string {
  return `https://fonts.adobe.com/search?query=${encodeURIComponent(name)}`;
}

export function fontStoreUrl(font: FontMatch): string {
  return font.source === "google" ? googleFontsUrl(font.name) : adobeFontsUrl(font.name);
}
